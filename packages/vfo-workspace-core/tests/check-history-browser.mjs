import assert from 'node:assert/strict';
import {fileURLToPath} from 'node:url';
import {mkdir,writeFile} from 'node:fs/promises';
import {chromium} from 'playwright';
const base=process.env.HISTORY_DEMO_URL??'http://127.0.0.1:5186';
const fixture=fileURLToPath(new URL('./synthetic-history.html',import.meta.url));
const out=process.env.HISTORY_EVIDENCE_DIR??'.review/history-integrated';
await mkdir(out,{recursive:true});
const browser=await chromium.launch({headless:true,...(process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE?{executablePath:process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE}:{}),args:['--no-sandbox']});
const page=await browser.newPage({viewport:{width:1500,height:950}}),errors=[];
page.on('pageerror',e=>errors.push(e.message));
try{
 await page.goto(base+'/@fs'+fixture);
 await page.getByTestId('ticker-tearsheet').waitFor();
 assert.equal(await page.evaluate(()=>window.historyFixture.calls.length),0,'Live mode must not fetch the archive');
 await page.getByRole('button',{name:'Historical',exact:true}).click();
 const browserRegion=page.getByRole('region',{name:'Saved date browser',exact:true});
 await page.waitForFunction(()=>document.querySelector('[aria-label="Saved date browser"]')?.getAttribute('aria-busy')==='false');
 assert.equal(await page.locator('input[type=date]').count(),0);
 assert.equal(await page.locator('.ops-period-cell').count(),27);
 const ranges=await page.evaluate(()=>window.historyFixture.calls);
 assert.equal(ranges[0].start,'2018-01-01');assert.equal(ranges.at(-1).end,'2026-11-01');
 assert.ok(ranges.every((r,i)=>(Date.parse(r.end)-Date.parse(r.start))/86400000<=366&&(!i||ranges[i-1].end===r.start)));
 assert.equal(await page.locator('.ops-period-fill .ops-quality-good').count()>0,true);
 await browserRegion.screenshot({path:out+'/years.png'});
 await page.locator('[data-period="2024"]').first().click();await page.locator('[data-history-level=month]').waitFor();
 assert.equal(await page.locator('.ops-period-cell').count(),36);
 await page.locator('[data-period="2024-02"]').first().focus();await page.keyboard.press('Enter');
 await page.locator('[data-history-level=day]').waitFor();assert.equal(await page.locator('.ops-period-cell').count(),87);
 await page.locator('[data-period="2024-02-29"]').nth(1).click();
 await page.getByText('Synthetic fixture: no surface artifact attached.',{exact:true}).waitFor();
 assert.deepEqual(await page.evaluate(()=>window.historyFixture.dayCalls),[{request:'synthetic-feed',date:'2024-02-29'}]);
 await page.getByRole('button',{name:'Coverage',exact:true}).click();
 assert.equal(await page.locator('.ops-period-cell[aria-pressed=true]').count(),1);
 assert.equal(await page.evaluate(()=>window.historyFixture.dayCalls.length),1);
 await page.getByRole('button',{name:'Fit quality',exact:true}).click();
 await browserRegion.screenshot({path:out+'/days.png'});
 await page.getByRole('navigation',{name:'History breadcrumbs'}).getByRole('button',{name:'All years',exact:true}).click();
 await page.locator('[data-history-level=year]').waitFor();await page.locator('[data-period="2019"]').first().click();
 await page.locator('[data-history-level=month]').waitFor();await page.locator('[data-period="2019-01"]').first().click();
 await page.locator('[data-history-level=day]').waitFor();
 assert.equal(await page.locator('[data-period="2019-01-01"]').nth(2).isDisabled(),true);
 assert.equal(await page.evaluate(()=>window.historyFixture.calls.length),ranges.length,'Drilling and lens changes must not refetch history');
 await page.emulateMedia({reducedMotion:'reduce'});
 await page.getByRole('button',{name:'Toggle fixture theme',exact:true}).click();
 await page.setViewportSize({width:390,height:900});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
 assert.ok(await page.locator('.ops-strip-scroll').evaluate(e=>e.scrollWidth>e.clientWidth));
 await page.getByRole('button',{name:'All years',exact:true}).click();await page.locator('[data-history-level=year]').waitFor();
 await browserRegion.screenshot({path:out+'/mobile-dark.png',animations:'disabled'});
 assert.deepEqual(errors,[]);
 const receipt={checks:['archive is lazy in live mode','full registered range in bounded contiguous requests','three sources','year/month/leap-day drilldown','exact source request and date','lens preserves selection without artifact reread','unknown dates disabled','navigation makes no further history requests','reduced motion','390px without page overflow','no browser errors'],historyRequests:ranges.length,errors};
 await writeFile(out+'/receipt.json',JSON.stringify(receipt,null,2));console.log(JSON.stringify(receipt));
}finally{await browser.close();}
